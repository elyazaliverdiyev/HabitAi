/** Поиск канонической версии по названию (для замены урезанных) */
export function findCanonical(title: string): CanonicalTransformation | undefined {
  const t = title.trim().toLowerCase();
  return CANONICAL_TRANSFORMATIONS.find(c =>
    c.title.toLowerCase() === t ||
    t.includes(c.title.toLowerCase()) ||
    c.title.toLowerCase().includes(t)
  );
}
