export async function generateAITransformation(
  situationDescription: string,
  language: 'ru' | 'en' = 'ru'
): Promise<AITransformationResult> {
  const prompt = language === 'ru'
    ? `Описание ситуации верующего:\n«${situationDescription}»\n\nСобери трансформацию.`
    : `Believer's situation:\n"${situationDescription}"\n\nBuild the transformation (answer fields in Russian except Name translit).`;

  const raw = await streamContent({
    contents: prompt,
    systemInstruction: SYSTEM_INSTRUCTION,
    temperature: 0.7,
    onChunk: () => {}, // JSON собираем целиком, стрим не нужен
  });

  const jsonStr = extractJson(raw);
  const parsed = JSON.parse(jsonStr) as AITransformationResult;

  // Валидация обязательных полей
  if (!parsed.formula || !parsed.nameTranslit || !parsed.checkQuestion) {
    throw new Error('AI response missing required fields');
  }

  return parsed;
}
